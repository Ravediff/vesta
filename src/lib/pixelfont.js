const WIDTH = 5;
const HEIGHT = 7;
const ADVANCE = 6; // glyph width + 1 column gap

const supports = text => [...String(text).toUpperCase()].every(ch => ch in GLYPHS);

const measure = (text, scale) => Math.max(0, [...String(text)].length * ADVANCE * scale - scale);

// Draws text with square pixels. align: 'left' | 'center' | 'right'.
// shadow: colour of a 1-pixel drop shadow (in font pixels), or null.
function draw(ctx, text, x, y, { scale = 4, color = '#fff', align = 'left', shadow = null } = {}) {
  const chars = [...String(text).toUpperCase()];
  const width = measure(text, scale);
  let left = align === 'center' ? x - width / 2 : align === 'right' ? x - width : x;
  left = Math.round(left);

  const paint = (ox, oy, fill) => {
    ctx.fillStyle = fill;
    chars.forEach((ch, i) => {
      const glyph = GLYPHS[ch] ?? GLYPHS['?'];
      for (let row = 0; row < HEIGHT; row++) {
        for (let col = 0; col < WIDTH; col++) {
          if (glyph[row][col] === '#') {
            ctx.fillRect(left + ox + (i * ADVANCE + col) * scale, y + oy + row * scale, scale, scale);
          }
        }
      }
    });
  };

  if (shadow) paint(scale, scale, shadow);
  paint(0, 0, color);
  return width;
}

module.exports = { draw, measure, supports, HEIGHT };
